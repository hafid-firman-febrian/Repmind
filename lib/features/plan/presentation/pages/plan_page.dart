class PlanPage extends ConsumerWidget {
  const PlanPage({super.key});

  Future<void> _adjust(
    BuildContext context,
    WidgetRef ref,
    WorkoutPlan plan,
  ) async {
    final instruction = await showAdjustPlanSheet(
      context,
      currentVersion: plan.version,
    );
    if (instruction == null || !context.mounted) return;
    startPlanGeneration(context, ref, instruction: instruction);
  }

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final plan = currentPlanOf(ref.watch(activePlanControllerProvider));

    return Scaffold(
      body: SafeArea(
        bottom: false,
        child: ListView(
          padding: EdgeInsets.fromLTRB(
            20,
            16,
            20,
            MediaQuery.paddingOf(context).bottom + 24,
          ),
          children: [
            Row(
              children: [
                Expanded(
                  child: Text('YOUR PLAN', style: context.textStyles.title),
                ),
                if (plan != null)
                  SquareIconButton(
                    icon: Icons.auto_awesome_rounded,
                    tooltip: 'Adjust plan',
                    ai: true,
                    onPressed: () => _adjust(context, ref, plan),
                  ),
              ],
            ),
            const SizedBox(height: 16),
            ActivePlanSection(
              builder: (context, plan) => _PlanContent(plan: plan),
            ),
          ],
        ),
      ),
    );
  }
}

class _PlanContent extends ConsumerWidget {
  const _PlanContent({required this.plan});

  final WorkoutPlan plan;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final today = ref.watch(clockProvider)().weekday;
    final instruction = plan.instruction;

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        HeroCard(
          badge: TagBadge(
            label: 'Generated by AI · v${plan.version}',
            showSparkle: true,
          ),
          title: plan.title,
          meta: 'Made with ${plan.aiModel.label}',
          footer: Wrap(
            spacing: 8,
            runSpacing: 8,
            children: [
              HeroChip(label: plan.goal.label),
              HeroChip(label: plan.level.label),
            ],
          ),
        ),
        if (instruction != null) ...[
          const SizedBox(height: 12),
          AdjustedNote(instruction: instruction),
        ],
        const SizedBox(height: 24),
        Text('WEEK SCHEDULE', style: context.textStyles.section),
        const SizedBox(height: 12),
        for (final day in plan.days)
          Padding(
            padding: const EdgeInsets.only(bottom: 10),
            child: PlanDayTile(
              badge: 'D${day.dayNumber}',
              title: day.title,
              subtitle: daySubtitle(day),
              trailing: weekdayShort(day.weekday),
              isToday: day.weekday == today,
              onTap: () =>
                  context.push(AppRoutes.workoutDayPath(day.dayNumber)),
            ),
          ),
      ],
    );
  }
}
