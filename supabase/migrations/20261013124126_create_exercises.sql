create type public.workout_focus as enum ('upper', 'lower', 'core', 'full_body');

create table public.exercises (
  id              text primary key check (id ~ '^[a-z0-9_]+$'),
  name            text not null unique,
  focus           public.workout_focus not null,
  primary_muscle  text not null,
  equipment       public.equipment[] not null default '{}'
);

alter table public.exercises enable row level security;

create policy "Authenticated users can read the exercise catalog"
  on public.exercises for select to authenticated
  using (true);

