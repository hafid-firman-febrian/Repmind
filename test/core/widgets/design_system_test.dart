import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:repmind/core/theme/repmind_colors.dart';
import 'package:repmind/core/widgets/hero_card.dart';
import 'package:repmind/core/widgets/option_chip.dart';
import 'package:repmind/core/widgets/primary_button.dart';
import 'package:repmind/core/widgets/selectable_card.dart';
import 'package:repmind/core/widgets/stat_tile.dart';
import 'package:repmind/core/widgets/tag_badge.dart';

import '../../helpers/pump_app.dart';

void main() {
  testWidgets('HeroCard shows badge, uppercase title, meta and watermark', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const HeroCard(
        badge: TagBadge(label: 'Your profile'),
        title: 'Build muscle',
        meta: 'Intermediate · 4 days/week',
        watermark: '04',
      ),
    );

    expect(find.text('YOUR PROFILE'), findsOneWidget);
    expect(find.text('BUILD MUSCLE'), findsOneWidget);
    expect(find.text('Intermediate · 4 days/week'), findsOneWidget);
    expect(find.text('04'), findsOneWidget);
  });

  testWidgets('TagBadge marks AI content with a violet sparkle', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const TagBadge(label: 'Generated by AI', showSparkle: true),
    );

    final sparkle = tester.widget<Icon>(
      find.byIcon(Icons.auto_awesome_rounded),
    );
    expect(sparkle.color, RepmindColors.light.violet);
  });

  testWidgets('StatTile fills with orange only when highlighted', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const Column(
        children: [
          StatTile(value: '72.5 kg', label: 'Weight', highlighted: true),
          StatTile(value: '175 cm', label: 'Height'),
        ],
      ),
    );

    Color? fillOf(String label) {
      final tile = tester.widget<Container>(
        find
            .ancestor(of: find.text(label), matching: find.byType(Container))
            .first,
      );
      return (tile.decoration! as BoxDecoration).color;
    }

    expect(fillOf('Weight'), RepmindColors.light.orange);
    expect(fillOf('Height'), RepmindColors.light.surface);
  });

  testWidgets('PrimaryButton shows a spinner and ignores taps while loading', (
    tester,
  ) async {
    var taps = 0;
    await pumpThemed(
      tester,
      PrimaryButton(label: 'Save', isLoading: true, onPressed: () => taps++),
    );

    await tester.tap(find.byType(PrimaryButton));
    expect(find.byType(CircularProgressIndicator), findsOneWidget);
    expect(find.text('Save'), findsNothing);
    expect(taps, 0);
  });

  testWidgets('SelectableCard fills with lime when selected', (tester) async {
    await pumpThemed(
      tester,
      SelectableCard(title: 'Build muscle', selected: true, onTap: () {}),
    );

    final material = tester.widget<Material>(
      find
          .descendant(
            of: find.byType(SelectableCard),
            matching: find.byType(Material),
          )
          .first,
    );
    expect(material.color, RepmindColors.light.lime);
  });

  testWidgets('OptionChip reports taps', (tester) async {
    var tapped = false;
    await pumpThemed(
      tester,
      OptionChip(
        label: 'Dumbbells',
        selected: false,
        onTap: () => tapped = true,
      ),
    );

    await tester.tap(find.text('Dumbbells'));
    expect(tapped, isTrue);
  });
}
