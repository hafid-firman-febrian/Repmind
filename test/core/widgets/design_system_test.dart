import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:repmind/core/theme/repmind_colors.dart';
import 'package:repmind/core/widgets/hero_card.dart';
import 'package:repmind/core/widgets/option_chip.dart';
import 'package:repmind/core/widgets/primary_button.dart';
import 'package:repmind/core/widgets/repmind_text_field.dart';
import 'package:repmind/core/widgets/selectable_card.dart';
import 'package:repmind/core/widgets/square_icon_button.dart';
import 'package:repmind/core/widgets/stat_tile.dart';
import 'package:repmind/core/widgets/tag_badge.dart';

import '../../helpers/pump_app.dart';

void main() {
  testWidgets('HeroCard shows badge, uppercase title, meta and watermark', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const HeroCard(
        badge: TagBadge(label: 'Your profile'),
        title: 'Build muscle',
        meta: 'Intermediate · 4 days/week',
        watermark: '04',
      ),
    );

    expect(find.text('YOUR PROFILE'), findsOneWidget);
    expect(find.text('BUILD MUSCLE'), findsOneWidget);
    expect(find.text('Intermediate · 4 days/week'), findsOneWidget);
    expect(find.text('04'), findsOneWidget);
  });

  testWidgets('TagBadge marks AI content with a violet sparkle', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const TagBadge(label: 'Generated by AI', showSparkle: true),
    );

    final sparkle = tester.widget<Icon>(
      find.byIcon(Icons.auto_awesome_rounded),
    );
    expect(sparkle.color, RepmindColors.light.violet);
  });

  testWidgets('StatTile fills with orange only when highlighted', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const Column(
        children: [
          StatTile(value: '72.5 kg', label: 'Weight', highlighted: true),
          StatTile(value: '175 cm', label: 'Height'),
        ],
      ),
    );

    Color? fillOf(String label) {
      final tile = tester.widget<Container>(
        find
            .ancestor(of: find.text(label), matching: find.byType(Container))
            .first,
      );
      return (tile.decoration! as BoxDecoration).color;
    }

    expect(fillOf('Weight'), RepmindColors.light.orange);
    expect(fillOf('Height'), RepmindColors.light.surface);
  });

  testWidgets('PrimaryButton shows a spinner and ignores taps while loading', (
    tester,
  ) async {
    var taps = 0;
    await pumpThemed(
      tester,
      PrimaryButton(label: 'Save', isLoading: true, onPressed: () => taps++),
    );

    await tester.tap(find.byType(PrimaryButton));
    expect(find.byType(CircularProgressIndicator), findsOneWidget);
    expect(find.text('Save'), findsNothing);
    expect(taps, 0);
  });

  testWidgets('SelectableCard fills with lime when selected', (tester) async {
    await pumpThemed(
      tester,
      SelectableCard(title: 'Build muscle', selected: true, onTap: () {}),
    );

    final material = tester.widget<Material>(
      find
          .descendant(
            of: find.byType(SelectableCard),
            matching: find.byType(Material),
          )
          .first,
    );
    expect(material.color, RepmindColors.light.lime);
  });

  testWidgets('OptionChip reports taps', (tester) async {
    var tapped = false;
    await pumpThemed(
      tester,
      OptionChip(
        label: 'Dumbbells',
        selected: false,
        onTap: () => tapped = true,
      ),
    );

    await tester.tap(find.text('Dumbbells'));
    expect(tapped, isTrue);
  });
  testWidgets('RepmindTextField lets the user reveal a hidden password', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const RepmindTextField(label: 'Password', obscureText: true),
    );

    bool isObscured() =>
        tester.widget<EditableText>(find.byType(EditableText)).obscureText;

    expect(isObscured(), isTrue);

    await tester.tap(find.byTooltip('Show password'));
    await tester.pump();

    expect(isObscured(), isFalse);

    await tester.tap(find.byTooltip('Hide password'));
    await tester.pump();

    expect(isObscured(), isTrue);
  });

  testWidgets('RepmindTextField shows no reveal button for plain fields', (
    tester,
  ) async {
    await pumpThemed(tester, const RepmindTextField(label: 'Email'));

    expect(find.byType(IconButton), findsNothing);
  });

  testWidgets('PrimaryButton ai variant is violet with a sparkle', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      PrimaryButton(
        label: 'Generate my plan',
        variant: PrimaryButtonVariant.ai,
        onPressed: () {},
      ),
    );

    final style = tester.widget<FilledButton>(find.byType(FilledButton)).style!;
    expect(
      style.backgroundColor!.resolve(<WidgetState>{}),
      RepmindColors.light.violet,
    );
    expect(
      style.foregroundColor!.resolve(<WidgetState>{}),
      RepmindColors.light.onViolet,
    );
    expect(find.byIcon(Icons.auto_awesome_rounded), findsOneWidget);
    expect(find.text('Generate my plan'), findsOneWidget);
  });

  testWidgets('SquareIconButton ai variant uses the violet tint', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      SquareIconButton(
        icon: Icons.auto_awesome_rounded,
        tooltip: 'Adjust plan',
        ai: true,
        onPressed: () {},
      ),
    );

    final icon = tester.widget<Icon>(find.byIcon(Icons.auto_awesome_rounded));
    final material = tester.widget<Material>(
      find
          .ancestor(
            of: find.byIcon(Icons.auto_awesome_rounded),
            matching: find.byType(Material),
          )
          .first,
    );
    expect(icon.color, RepmindColors.light.violet);
    expect(material.color, RepmindColors.light.violetTint);
  });

  testWidgets('RepmindTextField supports multi-line input with a limit', (
    tester,
  ) async {
    await pumpThemed(
      tester,
      const RepmindTextField(
        label: 'Instruction',
        minLines: 3,
        maxLines: 5,
        maxLength: 200,
      ),
    );

    final field = tester.widget<TextField>(find.byType(TextField));
    expect(field.minLines, 3);
    expect(field.maxLines, 5);
    expect(field.maxLength, 200);
    expect(find.text('0/200'), findsOneWidget);
  });
}
