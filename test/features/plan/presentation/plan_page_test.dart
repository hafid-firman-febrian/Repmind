import 'dart:async';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:go_router/go_router.dart';
import 'package:mocktail/mocktail.dart';
import 'package:repmind/core/errors/app_exception.dart';
import 'package:repmind/core/router/app_routes.dart';
import 'package:repmind/core/time/clock_provider.dart';
import 'package:repmind/core/widgets/option_chip.dart';
import 'package:repmind/features/auth/presentation/controllers/auth_status_provider.dart';
import 'package:repmind/features/plan/data/repositories/plan_repository.dart';
import 'package:repmind/features/plan/domain/models/workout_plan_model.dart';
import 'package:repmind/features/plan/presentation/controllers/active_plan_controller.dart';
import 'package:repmind/features/plan/presentation/controllers/plan_generation_controller.dart';
import 'package:repmind/features/plan/presentation/pages/generating_page.dart';
import 'package:repmind/features/plan/presentation/pages/plan_page.dart';
import 'package:repmind/features/profile/presentation/controllers/profile_controller.dart';

import '../../../fakes/fake_active_plan_controller.dart';
import '../../../fakes/fake_plan_generation_controller.dart';
import '../../../fakes/fake_profile_controller.dart';
import '../../../fixtures/plan_fixtures.dart';
import '../../../fixtures/profile_fixtures.dart';
import '../../../helpers/mocks.dart';
import '../../../helpers/pump_router.dart';

void main() {
  final tuesday = DateTime(2026, 10, 13, 9);
  late FakePlanGenerationController generation;

  Future<void> pumpPlan(
    WidgetTester tester, {
    WorkoutPlan? plan,
    Object? loadError,
  }) async {
    useTallScreen(tester);
    generation = FakePlanGenerationController();
    await pumpRouter(
      tester,
      initialLocation: AppRoutes.plan,
      overrides: [
        activePlanControllerProvider.overrideWith(
          () => FakeActivePlanController(plan, loadError: loadError),
        ),
        planGenerationControllerProvider.overrideWith(() => generation),
        clockProvider.overrideWithValue(() => tuesday),
      ],
      routes: [
        GoRoute(path: AppRoutes.plan, builder: (_, _) => const PlanPage()),
        GoRoute(
          path: AppRoutes.workoutDay,
          builder: (_, state) => Text('workout ${state.pathParameters['day']}'),
        ),
        GoRoute(
          path: AppRoutes.generating,
          builder: (_, _) => const Text('generating'),
        ),
      ],
    );
    await tester.pump();
  }

  Future<GoRouter> pumpWithRepository(
    WidgetTester tester,
    MockPlanRepository repository, {
    required Widget generatingPage,
  }) async {
    useTallScreen(tester);
    final router = await pumpRouter(
      tester,
      initialLocation: AppRoutes.plan,
      overrides: [
        currentUserIdProvider.overrideWithValue('user-1'),
        planRepositoryProvider.overrideWithValue(repository),
        profileControllerProvider.overrideWith(
          () => FakeProfileController(sampleProfile()),
        ),
        clockProvider.overrideWithValue(() => tuesday),
      ],
      routes: [
        GoRoute(path: AppRoutes.plan, builder: (_, _) => const PlanPage()),
        GoRoute(path: AppRoutes.generating, builder: (_, _) => generatingPage),
      ],
    );
    await tester.pump();
    return router;
  }

  testWidgets('shows an adjusted plan with its version, model and week', (
    tester,
  ) async {
    await pumpPlan(
      tester,
      plan: samplePlan(version: 2, instruction: 'More core work'),
    );

    expect(find.text('YOUR PLAN'), findsOneWidget);
    expect(find.byTooltip('Adjust plan'), findsOneWidget);
    expect(find.text('GENERATED BY AI · V2'), findsOneWidget);
    expect(find.text('4-DAY UPPER / LOWER'), findsOneWidget);
    expect(find.text('Made with Gemini 3.8 Flash'), findsOneWidget);
    expect(find.text('Build muscle'), findsOneWidget);
    expect(find.text('Intermediate'), findsOneWidget);
    expect(find.text('Adjusted: “More core work”'), findsOneWidget);
    expect(find.text('WEEK SCHEDULE'), findsOneWidget);
    expect(find.text('D1'), findsOneWidget);
    expect(find.text('Upper · 6 exercises'), findsOneWidget);
    expect(find.text('TODAY'), findsOneWidget);
    expect(find.text('Thu'), findsOneWidget);
    expect(find.text('Tue'), findsNothing);
  });

  testWidgets('a first plan has no adjusted note', (tester) async {
    await pumpPlan(tester, plan: samplePlan());

    expect(find.text('GENERATED BY AI · V1'), findsOneWidget);
    expect(find.textContaining('Adjusted'), findsNothing);
  });

  testWidgets('opens a day from the schedule', (tester) async {
    await pumpPlan(tester, plan: samplePlan());

    await tester.tap(find.text('Legs & Core'));
    await tester.pumpAndSettle();

    expect(find.text('workout 3'), findsOneWidget);
  });

  testWidgets('adjusting asks for an instruction and starts the next version', (
    tester,
  ) async {
    await pumpPlan(tester, plan: samplePlan(version: 2));

    await tester.tap(find.byTooltip('Adjust plan'));
    await tester.pumpAndSettle();
    await tester.tap(find.widgetWithText(OptionChip, 'More core work'));
    await tester.pump();
    await tester.tap(find.text('Generate v3'));
    await tester.pumpAndSettle();

    expect(generation.generateCalls, ['More core work']);
    expect(find.text('generating'), findsOneWidget);
  });

  testWidgets('without a plan offers to generate one', (tester) async {
    await pumpPlan(tester);

    expect(find.byTooltip('Adjust plan'), findsNothing);
    expect(find.text('YOUR AI PLAN'), findsOneWidget);
    expect(
      find.text(
        'Gemini builds a weekly plan from your goal, level and equipment.',
      ),
      findsOneWidget,
    );

    await tester.tap(find.text('Generate my plan'));
    await tester.pumpAndSettle();

    expect(generation.generateCalls, [null]);
    expect(find.text('generating'), findsOneWidget);
  });

  testWidgets('offers a retry when the plan cannot be loaded', (tester) async {
    await pumpPlan(tester, loadError: const NetworkFailure());

    expect(find.text(const NetworkFailure().message), findsOneWidget);
    expect(find.text('Try again'), findsOneWidget);
  });

  testWidgets(
    'a saved adjustment that fails to reload shows the error, not the old plan',
    (tester) async {
      final repository = MockPlanRepository();
      var loads = 0;
      when(() => repository.fetchActivePlan('user-1')).thenAnswer((_) async {
        loads++;
        if (loads == 1) return samplePlan();
        if (loads == 2) throw const NetworkFailure();
        return samplePlan(version: 2, instruction: 'More core work');
      });
      final saving = Completer<String>();
      when(
        () => repository.generatePlan(instruction: 'More core work'),
      ).thenAnswer((_) => saving.future);
      await pumpWithRepository(
        tester,
        repository,
        generatingPage: const GeneratingPage(),
      );
      expect(find.text('GENERATED BY AI · V1'), findsOneWidget);

      await tester.tap(find.byTooltip('Adjust plan'));
      await tester.pumpAndSettle();
      await tester.tap(find.widgetWithText(OptionChip, 'More core work'));
      await tester.pump();
      await tester.tap(find.text('Generate v2'));
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 500));
      expect(find.text('ADJUSTING YOUR PLAN'), findsOneWidget);

      saving.complete('plan-2');
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 500));

      expect(find.text('ADJUSTING YOUR PLAN'), findsNothing);
      expect(find.text(const NetworkFailure().message), findsOneWidget);
      expect(find.text('Try again'), findsOneWidget);
      expect(find.text('GENERATED BY AI · V1'), findsNothing);
      expect(find.byTooltip('Adjust plan'), findsNothing);

      await tester.tap(find.text('Try again'));
      await tester.pump();
      await tester.pump();

      expect(find.text('GENERATED BY AI · V2'), findsOneWidget);
      expect(find.byTooltip('Adjust plan'), findsOneWidget);
      verify(
        () => repository.generatePlan(instruction: 'More core work'),
      ).called(1);
    },
  );
  testWidgets('a fast double tap opens the generating page once', (
    tester,
  ) async {
    final repository = MockPlanRepository();
    when(
      () => repository.fetchActivePlan('user-1'),
    ).thenAnswer((_) async => null);
    when(
      () => repository.generatePlan(instruction: null),
    ).thenAnswer((_) => Completer<String>().future);
    final router = await pumpWithRepository(
      tester,
      repository,
      generatingPage: const Text('generating'),
    );

    await tester.tap(find.text('Generate my plan'));
    await tester.tap(find.text('Generate my plan'));
    await tester.pumpAndSettle();

    expect(find.text('generating'), findsOneWidget);

    router.pop();
    await tester.pumpAndSettle();

    expect(find.text('generating'), findsNothing);
    expect(find.text('YOUR AI PLAN'), findsOneWidget);
    verify(() => repository.generatePlan(instruction: null)).called(1);
  });
}
